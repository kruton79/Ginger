n=15
result=0
print("перевірка для числа", n)
for s in range(1, n+1):  #задаю діапазон для змінної s
    if n%s == 0:  #умова для знаходження дільників числа n
        result = result + s
        print(s)
if (result-n)%n == 0: # умова для перевірки чи є число досконалим
     print("число є досконалим") 
else:
     print("число не є досконалим") 




